// Canonical skill names (as stored in the skills table) and the patterns that detect them in a
// job description. Used when importing scraped postings.
const patterns: [string, RegExp][] = [
  ["TypeScript", /\btypescript\b/i],
  ["JavaScript", /\bjavascript\b/i],
  ["React", /\breact(?:\.js|js)?\b(?!\s*native)/i],
  ["React Native", /\breact\s*native\b/i],
  ["Next.js", /\bnext(?:\.js|js)\b/i],
  ["Node.js", /\bnode(?:\.js|js)?\b/i],
  ["NestJS", /\bnest(?:\.js|js)\b/i],
  ["Express", /\bexpress(?:\.js|js)?\b/i],
  ["PostgreSQL", /\bpostgres(?:ql)?\b/i],
  ["MySQL", /\bmysql\b/i],
  ["MongoDB", /\bmongo(?:db)?\b/i],
  ["Redis", /\bredis\b/i],
  ["GraphQL", /\bgraphql\b/i],
  ["Google Cloud", /\b(?:gcp|google cloud)\b/i],
  ["Firebase", /\bfirebase\b/i],
  ["AWS", /\b(?:aws|amazon web services)\b/i],
  ["Azure", /\bazure\b/i],
  ["Docker", /\bdocker\b/i],
  ["Kubernetes", /\b(?:kubernetes|k8s)\b/i],
  ["Terraform", /\bterraform\b/i],
  ["CI/CD", /\bci\s*\/\s*cd\b/i],
  ["Python", /\bpython\b/i],
  ["Django / FastAPI", /\b(?:django|fastapi)\b/i],
  ["C# / .NET", /(?:\bc#|\.net\b)/i],
  ["PHP / Laravel", /\b(?:php|laravel)\b/],
  ["Vue", /\bvue(?:\.js|js)?\b/i],
  ["Angular", /\bangular\b/i],
  ["Tailwind CSS", /\btailwind\b/i],
  ["Jest", /\bjest\b/i],
  ["Cypress", /\bcypress\b/i],
  ["Playwright", /\bplaywright\b/i],
  ["Kafka", /\bkafka\b/i],
  ["RabbitMQ", /\brabbitmq\b/i],
  ["Microservices", /\bmicro-?services\b/i],
  ["LLM integration", /\b(?:llms?|large language models?)\b/i],
  ["OpenAI API", /\bopenai\b/i],
  ["LangChain", /\blangchain\b/i],
  ["RAG", /\b(?:rag|retrieval[- ]augmented)\b/],
  ["Supabase", /\bsupabase\b/i],
  ["Vercel", /\bvercel\b/i],
  ["Serverless", /\bserverless\b/i],
  ["Elasticsearch", /\belastic\s*search\b/i],
  ["Shopify", /\bshopify\b/i],
];

export function detectSkills(text: string) {
  return patterns.filter(([, pattern]) => pattern.test(text)).map(([name]) => name);
}
